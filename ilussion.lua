	local function new(class, props, kids)
		local inst = Instance.new(class)
		local parent = nil
		if props then
			for key, value in pairs(props) do
				if key == "Parent" then
					parent = value
				else
					inst[key] = value
				end
			end
		end
		if kids then
			for _, kid in ipairs(kids) do
				kid.Parent = inst
			end
		end
		inst.Parent = parent
		return inst
	end

	-- Decided once, on the first shape built: either every surface is a generated
	-- superellipse, or every surface falls back to UICorner. Never a mix.
	local SQUIRCLE = nil
	local CP, TP = "BackgroundColor3", "BackgroundTransparency"

	local function shape(radius, props, kids)
		props = props or {}
		local color = props.Color
		local transparency = props.Transparency
		props.Color, props.Transparency = nil, nil

		local inst
		if SQUIRCLE ~= false then
			local img = Instance.new("ImageLabel")
			img.BackgroundTransparency = 1
			img.BorderSizePixel = 0
			local ok = Draw.squircle(img, radius)
			if SQUIRCLE == nil then
				SQUIRCLE = ok
				if ok then
					CP, TP = "ImageColor3", "ImageTransparency"
				end
			end
			if ok then
				inst = img
			else
				img:Destroy()
			end
		end

		if not inst then
			inst = Instance.new("Frame")
			inst.BorderSizePixel = 0
			new("UICorner", { CornerRadius = UDim.new(0, radius), Parent = inst })
		end

		inst[CP] = color or C.Card
		inst[TP] = transparency or 0

		local parent = props.Parent
		props.Parent = nil
		for key, value in pairs(props) do
			inst[key] = value
		end
		if kids then
			for _, kid in ipairs(kids) do
				kid.Parent = inst
			end
		end
		inst.Parent = parent
		return inst
	end

	--[[
		Hairline border for a squircle surface.

		Not UIStroke: that traces the GuiObject's rectangle and would draw a box
		around a rounded shape. This is a ring texture laid over the fill. As a child
		it always renders above its parent's own image, which is what we want — the
		ring is hollow, so only the 1px edge lands on top. ZIndex 0 keeps it under
		the surface's real content.

		In the UICorner fallback there is no image to mismatch, so UIStroke is
		correct there and we use it.
	]]
	local function outline(surface, radius, color, transparency)
		if SQUIRCLE == false then
			return new("UIStroke", {
				Parent = surface,
				Color = color or C.Stroke,
				Thickness = 1,
				Transparency = transparency or 0,
			})
		end

		local ring = new("ImageLabel", {
			Parent = surface,
			BackgroundTransparency = 1,
			Size = UDim2.fromScale(1, 1),
			ImageColor3 = color or C.Stroke,
			ImageTransparency = transparency or 0,
			ZIndex = 0,
		})
		if not Draw.outline(ring, radius, 1) then
			ring:Destroy()
			return nil
		end
		return ring
	end

	local function circle(props, kids)
		local inst = new("Frame", props, kids)
		inst.BorderSizePixel = 0
		new("UICorner", { CornerRadius = UDim.new(1, 0), Parent = inst })
		return inst
	end

