	function Library:CreateWindow(cfg)
		cfg = cfg or {}
		local size = cfg.Size or S.Window

		local gui = new("ScreenGui", {
			Name = cfg.Name or "AppleUI",
			ResetOnSpawn = false,
			IgnoreGuiInset = true,
			ZIndexBehavior = Enum.ZIndexBehavior.Sibling,
			DisplayOrder = 999,
		})
		if cfg.Parent then
			gui.Parent = cfg.Parent
		else
			mount(gui)
		end

		-- one CanvasGroup for the whole window: it owns the drag position, the
		-- entrance scale and the fade
		local root = new("CanvasGroup", {
			Parent = gui,
			BackgroundTransparency = 1,
			AnchorPoint = Vector2.new(0.5, 0.5),
			Position = UDim2.fromScale(0.5, 0.5),
			Size = UDim2.fromOffset(size.X, size.Y),
			GroupTransparency = 1,
		})
		local scale = new("UIScale", { Parent = root, Scale = 0.94 })

