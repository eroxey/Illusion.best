local __modules = {}
local __loaded = {}

local function __require(name)
	local cached = __loaded[name]
	if cached ~= nil then
		return cached
	end
	local factory = __modules[name]
	if not factory then
		error("unknown module: " .. tostring(name), 2)
	end
	local result = factory()
	__loaded[name] = result
	return result
end


